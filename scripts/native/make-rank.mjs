// ── Kotlin ──────────────────────────────────────────────────────────────────

const kotlinRungs = rungs
  .map(
    (r) =>
      `    Rung("${r.tier}", ${r.division}, ${r.index}, ${r.base}, ${r.span}),`,
  )
  .join('\n');

const kotlin = `// GENERATED by scripts/native/make-rank.mjs from src/domain/ranked.ts.
// Do not edit: re-run the script instead.
package app.revisio.engine

import kotlin.math.ceil
import kotlin.math.roundToInt

/**
 * The ladder, read out of the web's \`domain/ranked.ts\`.
 *
 * The server decides a learner's rank; this exists because the ladder screen
 * draws all ${rungs.length} rungs, and the ones nobody has reached are not
 * facts about anybody. Everything here is a constant of the game, so it can be
 * generated once and checked in.
 */
object RankLadder {
    /** RP per unit of XP. The two currencies are deliberately the same size. */
    const val RP_PER_XP = ${rpPerXp}

    /** Placements before a rank is awarded. */
    const val PLACEMENT_REVIEWS = ${placementReviews}

    /** Rough XP one review is worth, for "about N reviews" copy. */
    const val REVIEWS_PER_RP = 10

    /** A lobby promotes the top share of its seats, floored and capped. */
    const val ZONE_BAND_SHARE = 0.17
    const val ZONE_BAND_MIN = 1
    const val ZONE_BAND_MAX = 5

    val TIER_ORDER: List<String> = listOf(${TIER_ORDER.map((t) => `"${t}"`).join(', ')})

    val DIVISION_SPAN: Map<String, Int> = mapOf(
${TIER_ORDER.map((t) => `        "${t}" to ${DIVISION_SPAN[t]},`).join('\n')}
    )

    val DIVISION_LABEL: Map<Int, String> = mapOf(
${sortedDivisions.map((d) => `        ${d} to "${DIVISION_LABEL[d]}",`).join('\n')}
    )

    /** Within a tier we climb III → II → I. */
    val DIVISION_ORDER: List<Int> = listOf(${DIVISION_ORDER.join(', ')})

    /** One rung of the ladder, cumulative \`base\` and all. */
    data class Rung(
        val tier: String,
        val division: Int,
        val index: Int,
        val base: Int,
        val span: Int,
    )

    val rungs: List<Rung> = listOf(
${kotlinRungs}
    )

    /** Total RP needed to clear the whole ladder. */
    val TOP_OF_LADDER: Int = rungs.last().base

    fun tierName(tier: String): String =
        tier.replaceFirstChar { it.uppercaseChar() }

    fun rpForXp(totalXp: Int): Int = maxOf(0, (totalXp.toDouble() * RP_PER_XP).roundToInt())

    /** Which rung a quantity of RP sits on. Clamped at both ends. */
    fun rankFor(totalXp: Int): Rank {
        val points = rpForXp(totalXp)
        var rung = rungs.first()
        for (candidate in rungs) {
            if (points >= candidate.base) rung = candidate else break
        }
        val intoDivision = points - rung.base
        val isApex = rung.index == rungs.size - 1
        val percent = ((intoDivision.toDouble() / rung.span) * 100).roundToInt().coerceIn(0, 100)
        val label = "\${tierName(rung.tier)} \${DIVISION_LABEL[rung.division]}"
        return Rank(
            tier = rung.tier,
            division = rung.division,
            index = rung.index,
            label = label,
            short = "\${tierName(rung.tier).take(3).uppercase()} \${DIVISION_LABEL[rung.division]}",
            points = points,
            intoDivision = intoDivision,
            forDivision = rung.span,
            percent = percent,
            remaining = maxOf(0, rung.span - intoDivision),
            isApex = isApex,
        )
    }

    /** Rough reviews needed to earn an amount of RP. */
    fun reviewsForRp(rp: Int, perReview: Int = REVIEWS_PER_RP): Int =
        maxOf(1, ceil(rp.toDouble() / perReview).toInt())

    /**
     * The promotion and demotion bands inside a weekly lobby.
     *
     * Proportional, with a floor of one and a ceiling of five: a lobby of four
     * people should not promote three of them.
     */
    fun zoneBand(size: Int): Int =
        (size * ZONE_BAND_SHARE).roundToInt().coerceIn(ZONE_BAND_MIN, ZONE_BAND_MAX)
}
`;

// ── Swift ───────────────────────────────────────────────────────────────────

const swiftRungs = rungs
  .map((r) => `        Rung(tier: "${r.tier}", division: ${r.division}, index: ${r.index}, base: ${r.base}, span: ${r.span}),`)
  .join('\n');

