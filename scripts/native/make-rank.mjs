const targets = [
  ['mobile/android/engine/src/main/kotlin/app/revisio/engine/RankLadder.kt', kotlin],
  ['mobile/ios/Sources/RevisioEngine/RankLadder.swift', swift],
  ['mobile/android/engine/src/main/kotlin/app/revisio/engine/SrsLadder.kt', kotlinSrs],
  ['mobile/ios/Sources/RevisioEngine/SrsLadder.swift', swiftSrs],
];

for (const [path, contents] of targets) {
  const full = resolve(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, contents);
}

// A sanity check the generators can run instead of a test: the ladder must be a
// contiguous climb, or the rail would draw a gap nobody can cross.
for (let i = 1; i < rungs.length; i += 1) {
  const previous = rungs[i - 1];
  if (rungs[i].base !== previous.base + previous.span) {
    throw new Error(`make-rank: rung ${i} does not start where rung ${i - 1} ends`);
  }
}

console.log(
  `rank: ${rungs.length} rungs, ${TIER_ORDER.length} tiers, top of ladder ${rungs[rungs.length - 1].base} RP → RankLadder.kt, RankLadder.swift; srs: ${srsRungs.length} rungs → SrsLadder.kt, SrsLadder.swift`,
);
